public class relacional {

    public static void main(String[] args) {
        double num1 = 10.0;
        double num2 = 5.0;

        System.out.println("Comparando " + num1 + " e " + num2 + ":");
        System.out.println(num1 + " > " + num2 + ": " + (num1 > num2));
        System.out.println(num1 + " < " + num2 + ": " + (num1 < num2));
        System.out.println(num1 + " >= " + num2 + ": " + (num1 >= num2));
        System.out.println(num1 + " <= " + num2 + ": " + (num1 <= num2));
        System.out.println(num1 + " == " + num2 + ": " + (num1 == num2));
        System.out.println(num1 + " != " + num2 + ": " + (num1 != num2));
    }





    
}
