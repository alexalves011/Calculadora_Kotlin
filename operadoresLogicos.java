public class operadoresLogicos {
    

    public static void main(String[] args) {

        boolean condicao1 = true;
        boolean condicao2 = false;

        System.out.println("Condição 1: " + condicao1);
        System.out.println("Condição 2: " + condicao2);

        System.out.println("Condição 1 AND Condição 2: " + (condicao1 && condicao2));
        System.out.println("Condição 1 OR Condição 2: " + (condicao1 || condicao2));
        System.out.println("NOT Condição 1: " + (!condicao1));
    }
      


}
